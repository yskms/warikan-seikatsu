// 書き込みの最中は、招待URLによる参加確認への切り替えを遅らせる。
//
// 招待を持っているあいだ、ルート（`app/_layout.tsx` の `RootNavigator`）は、ログイン済みの画面を全部外して、参加確認だけを出す。
// `Stack.Protected` による除去は、`beforeRemove` を通らない（セッション切れと同じ。`ui/expense/ExpenseSheet.tsx`）ので、書き込みの
// 最中の画面も外れる。外れると、その書き込みの結果（成功したあとの画面遷移・失敗の表示）を受ける画面が無くなり、完了後に画面を戻す
// （`leave()`。`router.back()` / `router.replace()`）画面は、そのとき開いている別の画面に対して動きうる。そこで、書き込みの最中の
// 画面は、ここに登録して、**書き込みの通信が終わるまで、切り替えを遅らせる**（招待は、そのあいだ、持ったまま。終わったら、切り替わる）。
//
// **守る範囲は、通信の最中まで**。次は守らない（意図して、そうしている）:
// - **結果が分からない失敗（通信が切れた）のあと**: 失敗の文言を出して、画面が残っているあいだも遅らせる形にはしない（文言を閉じるまで
//   招待URLを開いても何も起きないように見え、いつまでも出ないことになる）。そのため、支出のシートの `id` は、このとき捨てられる。
//   保存されたかは、参加確認のあとに戻ったホームの一覧で分かる（保存されていれば、一覧に出る）。
// - **開いたままの確認ダイアログ**（削除の確認など）: 画面は外れ、ダイアログは残りうる（Androidの `Alert` は、Activityに付く。
//   未確認）。そこで押された操作は、画面が外れていれば何もしない（`ui/useMounted.ts`）。
//
// **登録するのは、書き込みを行い、結果を画面で受ける（完了後に遷移する、失敗を表示する）画面の、通信の最中**:
// 支出・月締め・カテゴリ編集のシート、グループ作成、メンバーと招待の招待の発行（トークンは発行の応答でしか分からず、画面のメモリに
// だけ持つので、発行の最中に外れると、招待はできるのに、トークンが失われ、未使用の招待として上限に数えられる）。新しくそうした画面を
// 作るときは、`useHoldInviteSwap(通信の最中か)` を呼び、完了後に遷移するなら、`useMounted`（`ui/useMounted.ts`）も使う。
// 読み込みの最中は、登録しない（外れても、取りこぼすものがない）。**参加確認の画面は、登録しない**（登録すると、参加の通信の最中に、
// 自分が外れる）。
//
// 遅らせる長さの上限: 通信には上限がある（`src/repositories/apiClient.ts` の `DEFAULT_TIMEOUT_MS`）。カテゴリ編集は、保存のあとの
// 「保存しました」のダイアログを閉じるまでも続く（その確認も、`busy` の中で待つ）が、目の前のダイアログを閉じるだけなので、許容する。
// 画面が消えれば、後始末で手放す。
import { useEffect, useSyncExternalStore } from 'react';

import { createHolds } from '../src/services/holds.ts';

const holds = createHolds();

/** `active` が真のあいだ、参加確認への切り替えを遅らせる（画面が消えたら、手放す）。 */
export function useHoldInviteSwap(active: boolean): void {
  useEffect(() => {
    if (!active) return;
    return holds.acquire();
  }, [active]);
}

/** 書き込みの最中の画面があるか（ルートが、参加確認への切り替えを遅らせるために見る）。 */
export function useInviteSwapHeld(): boolean {
  return useSyncExternalStore(
    holds.count.subscribe,
    () => holds.count.get() > 0,
    () => false,
  );
}
